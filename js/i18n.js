const RTL_LANGS = new Set(["ar"]);
const STORAGE_KEY = "lang";

function getSavedLang() {
  try { return localStorage.getItem(STORAGE_KEY); }
  catch { return null; }
}

function saveLang(lang) {
  try { localStorage.setItem(STORAGE_KEY, lang); }
  catch { /* unavailable */ }
}

function detectLang() {
  const saved = getSavedLang();
  if (saved && translations[saved]) return saved;

  const languages = navigator.languages || [(navigator.language || "en")];
  const langRegionMap = {
    "ar-sa": "ar", "ar-ae": "ar", "ar-eg": "ar", "ar-ma": "ar",
    "bn-bd": "bn", "bn-in": "bn",
    "id-id": "id", "id-mycar": "id",
    "en-gb": "en", "en-us": "en", "en-au": "en",
  };

  for (const lang of languages) {
    const lc = lang.toLowerCase();
    if (langRegionMap[lc]) return langRegionMap[lc];
    if (lc.startsWith("ar")) return "ar";
    if (lc.startsWith("bn")) return "bn";
    if (lc.startsWith("id")) return "id";
  }

  return "en";
}

function applyTranslations(lang) {
  const dict = translations[lang] || translations.en;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    const value = dict[key];
    if (value === undefined) return;
    if (el.tagName === "TITLE") {
      document.title = value;
    } else {
      el.textContent = value;
    }
  });

  const html = document.documentElement;
  html.lang = lang;
  html.dir = RTL_LANGS.has(lang) ? "rtl" : "ltr";

  document.querySelectorAll(".lang-btn").forEach((btn) => {
    const active = btn.dataset.lang === lang;
    btn.classList.toggle("is-active", active);
    btn.setAttribute("aria-pressed", String(active));
  });

  saveLang(lang);
}

function setLang(lang) {
  if (!translations[lang]) return;
  applyTranslations(lang);
}

function initI18n() {
  const lang = detectLang();
  applyTranslations(lang);
  document.querySelectorAll(".lang-btn").forEach((btn) => {
    btn.addEventListener("click", () => setLang(btn.dataset.lang));
  });
}

if (document.readyState === "loading") {
  document.addEventListener("DOMContentLoaded", initI18n);
} else {
  initI18n();
}
